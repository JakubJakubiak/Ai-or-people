import 'package:flutter/material.dart';
import 'package:humanai/utils/app_colors.dart';

/// Short introduction shown on first launch and from the settings menu.
class HowToPlayDialog extends StatelessWidget {
  const HowToPlayDialog({super.key});

  static Future<void> show(BuildContext context) {
    return showDialog<void>(context: context, builder: (_) => const HowToPlayDialog());
  }

  @override
  Widget build(BuildContext context) {
    return Dialog(
      backgroundColor: AppColors.surface,
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(28)),
      child: Padding(
        padding: const EdgeInsets.fromLTRB(22, 24, 22, 18),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            const Text(
              'Can you tell who made it?',
              textAlign: TextAlign.center,
              style: TextStyle(color: Colors.white, fontSize: 22, fontWeight: FontWeight.w900),
            ),
            const SizedBox(height: 18),
            const _Step(
              icon: Icons.visibility_rounded,
              color: AppColors.human,
              text: 'Look at the image, watch the video or listen to the music.',
            ),
            const _Step(
              icon: Icons.touch_app_rounded,
              color: AppColors.ai,
              text: 'Decide: was it made by a human or generated by AI?',
            ),
            const _Step(
              icon: Icons.lightbulb_rounded,
              color: AppColors.combo,
              text: 'After every answer you get a tip on what gives AI away.',
            ),
            const _Step(
              icon: Icons.local_fire_department_rounded,
              color: AppColors.wrong,
              text: 'Correct answers build your combo. Three mistakes end the run.',
            ),
            const SizedBox(height: 10),
            FilledButton(
              style: FilledButton.styleFrom(
                backgroundColor: Colors.white,
                foregroundColor: AppColors.background,
                minimumSize: const Size.fromHeight(52),
                shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
                textStyle: const TextStyle(fontSize: 17, fontWeight: FontWeight.w800),
              ),
              onPressed: () => Navigator.of(context).pop(),
              child: const Text("Let's play"),
            ),
          ],
        ),
      ),
    );
  }
}

class _Step extends StatelessWidget {
  const _Step({required this.icon, required this.color, required this.text});
  final IconData icon;
  final Color color;
  final String text;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 14),
      child: Row(
        children: [
          Container(
            width: 42,
            height: 42,
            decoration: BoxDecoration(color: color.withValues(alpha: 0.18), borderRadius: BorderRadius.circular(12)),
            child: Icon(icon, color: color, size: 24),
          ),
          const SizedBox(width: 14),
          Expanded(child: Text(text, style: const TextStyle(color: Colors.white, fontSize: 15, height: 1.3))),
        ],
      ),
    );
  }
}
